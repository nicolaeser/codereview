func TestHelpMarkdownListsCommands(t *testing.T) {
	body := HelpMarkdown("codereview")
	for _, want := range []string{
		"## CodeReview commands",
		"`@codereview skip`",
		"`@codereview review`",
		"`@codereview review <focus>`",
		"`@codereview full-review`",
		"`@codereview ask <question>`",
		"`@codereview prompt`",
		"`@codereview resolve`",
		"`@codereview help`",
		"`@codereview ignore`",
		"skip-codereview",
		"[skip review]",
		"silent by default",
		"Generated by CodeReview",
		helpMarker,
	} {
		if !strings.Contains(body, want) {
			t.Fatalf("help missing %q:\n%s", want, body)
		}
	}
	if ParseThreadCommand(body, []string{"codereview"}) != CommandNone {
		t.Fatal("posted help must not parse as skip or review")
	}
}

func TestParseMentionRequestExtraFocus(t *testing.T) {
	aliases := []string{"codereview"}
	got := ParseMentionRequest("@codereview review also check race conditions in worker.go", aliases)
	if got.Command != CommandReview || got.Extra != "also check race conditions in worker.go" {
		t.Fatalf("review extra = %#v", got)
	}
	for _, body := range []string{
		"@codereview full review look at SQL injection",
		"@codereview full-review look at SQL injection",
		"@codereview fullreview look at SQL injection",
	} {
		full := ParseMentionRequest(body, aliases)
		if full.Command != CommandFullReview || full.Extra != "look at SQL injection" {
			t.Fatalf("full extra for %q = %#v", body, full)
		}
	}
	ask := ParseMentionRequest("@codereview ask is this mutex held across the HTTP call?", aliases)
	if ask.Command != CommandAsk || !strings.Contains(ask.Extra, "mutex held") {
		t.Fatalf("ask extra = %#v", ask)
	}
	skip := ParseMentionRequest("@codereview skip because tests cover it", aliases)
	if skip.Command != CommandSkip || skip.Extra != "" {
		t.Fatalf("skip must not keep leftover: %#v", skip)
	}
	secret := ParseMentionRequest("@codereview review token AKIA0000000000FAKE00", aliases)
	if secret.Command != CommandReview || strings.Contains(secret.Extra, "AKIA0000000000FAKE00") {
		t.Fatalf("extra must be redacted: %#v", secret)
	}
	if ParseMentionRequest(FormatAskReply("hello"), aliases).Command != CommandNone {
		t.Fatal("posted ask reply must not parse as a command")
	}
}

func TestMRDisableTokenFromTitleAndLabel(t *testing.T) {
	tokens := []string{"skip-codereview", "[skip review]", "no-codereview"}
	if _, ok := mrDisableToken(gitlab.MergeRequest{Title: "Fix login"}, tokens); ok {
		t.Fatal("plain title must not disable")
	}
	if token, ok := mrDisableToken(gitlab.MergeRequest{Title: "WIP skip-codereview: experiments"}, tokens); !ok || token != "skip-codereview" {
		t.Fatalf("title token = %q ok=%t", token, ok)
	}
	if token, ok := mrDisableToken(gitlab.MergeRequest{Title: "Add API", Labels: []string{"backend", "no-codereview"}}, tokens); !ok || token != "no-codereview" {
		t.Fatalf("label token = %q ok=%t", token, ok)
	}
	if token, ok := mrDisableToken(gitlab.MergeRequest{Title: "chore: [skip review] docs"}, tokens); !ok {
		t.Fatalf("bracket token missing, got %q", token)
	}
}
