func TestNoteMentionsBot(t *testing.T) {
	aliases := []string{"codereview", "cr"}
	if !NoteMentionsBot("@codereview skip", aliases) {
		t.Fatal("expected mention of @codereview")
	}
	if !NoteMentionsBot("hey @CR please", aliases) {
		t.Fatal("expected alias match to be case-insensitive")
	}
	if NoteMentionsBot("please skip this", aliases) {
		t.Fatal("plain skip without mention must not match")
	}
}

func TestParseThreadCommand(t *testing.T) {
	aliases := []string{"codereview", "cr"}
	tests := []struct {
		body string
		want ThreadCommand
	}{
		{"@codereview that's a false positive, skip", CommandSkip},
		{"@codereview skip", CommandSkip},
		{"@codereview ignore", CommandSkip},
		{"@codereview false-positive", CommandSkip},
		{"@codereview please review", CommandReview},
		{"@codereview re-review this", CommandReview},
		{"@codereview full review", CommandFullReview},
		{"@codereview full-review", CommandFullReview},
		{"@codereview fullreview", CommandFullReview},
		{"@codereview full_review", CommandFullReview},
		{"@codereviewfullreview", CommandFullReview},
		{"@codereview resolve", CommandResolve},
		{"@codereview help", CommandHelp},
		{"@codereview ask why is this racy", CommandAsk},
		{"@codereview prompt explain the mutex", CommandAsk},
		{"@codereview question why atoi", CommandAsk},
		{"@codereviewprompt why atoi", CommandAsk},
		{"that's a false positive, skip", CommandNone},
		{"skip", CommandNone},
		{"@codereview", CommandHelp},
		{"@codereview thanks", CommandHelp},
		{"", CommandNone},
		{HelpMarkdown("codereview"), CommandNone},
	}
	for _, test := range tests {
		if got := ParseThreadCommand(test.body, aliases); got != test.want {
			t.Errorf("ParseThreadCommand(%q) = %s, want %s", test.body, got, test.want)
		}
	}
}

func TestHumanThreadCommandSkipAfterFindingNote(t *testing.T) {
	finding := Finding{Path: "main.go", Line: 3, Title: "Empty helper"}
	aliases := []string{"codereview"}
	skip := gitlab.Discussion{Notes: []gitlab.Note{
		{Body: "prior\n" + findingMarkerComment(FindingID(finding)), Author: gitlab.User{Username: "codereview"}},
		{Body: "@codereview that's a false positive, skip", Author: gitlab.User{Username: "dev"}},
	}}
	if got := humanThreadCommand(skip, aliases); got != CommandSkip {
		t.Fatalf("human skip = %s, want skip", got)
	}

	noMention := skip
	noMention.Notes[1].Body = "that's a false positive, skip"
	if got := humanThreadCommand(noMention, aliases); got != CommandNone {
		t.Fatalf("skip without mention = %s, want none", got)
	}

	bot := skip
	bot.Notes[1].Author = gitlab.User{Username: "project_1_bot_hash"}
	if got := humanThreadCommand(bot, aliases); got != CommandNone {
		t.Fatalf("automation skip = %s, want none", got)
	}

	inFinding := gitlab.Discussion{Notes: []gitlab.Note{
		{Body: "@codereview skip\n" + findingMarkerComment(FindingID(finding)), Author: gitlab.User{Username: "dev"}},
	}}
	if got := humanThreadCommand(inFinding, aliases); got != CommandNone {
		t.Fatalf("skip in finding note = %s, want none", got)
	}

	review := gitlab.Discussion{Notes: []gitlab.Note{
		{Body: findingMarkerComment(FindingID(finding)), Author: gitlab.User{Username: "codereview"}},
		{Body: "@codereview please review", Author: gitlab.User{Username: "dev"}},
	}}
	if got := humanThreadCommand(review, aliases); got != CommandReview {
		t.Fatalf("human review = %s, want review", got)
	}

	help := gitlab.Discussion{Notes: []gitlab.Note{
		{Body: findingMarkerComment(FindingID(finding)), Author: gitlab.User{Username: "codereview"}},
		{Body: "@codereview", Author: gitlab.User{Username: "dev"}},
	}}
	if got := humanThreadCommand(help, aliases); got != CommandHelp {
		t.Fatalf("bare mention = %s, want help", got)
	}
}

